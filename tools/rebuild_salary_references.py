def normal(text):
    text=re.sub(r'\([^)]*\)','',text.lower()).split(', except')[0]
    words=re.findall(r'[a-z]+',text)
    return ' '.join(w[:-3]+'y' if w.endswith('ies') else w[:-1] if w.endswith('s') and not w.endswith(('ss','ics')) else w for w in words)

